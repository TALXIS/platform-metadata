using System.Text;
using System.Text.Json.Nodes;

namespace TALXIS.Platform.Metadata.Serialization.Xml.Scaffolding;

/// <summary>
/// Writes src/generated/models/&lt;Name&gt;Model.ts and services/&lt;Name&gt;Service.ts and exports them from index.ts.
/// </summary>
internal static class LogicFlowTypeScriptFiles
{
    private const string Header = "/*!\n * Copyright (C) Microsoft Corporation. All rights reserved.\n * This file is autogenerated. Do not edit this file directly.\n */\n";

    public static void Write(string generatedDir, string modelName, string dataSourceName, PowerAppsFlowDefinition flow)
    {
        var model = new StringBuilder(Header);
        model.Append('\n');
        model.Append(RenderInterface("ManualTriggerInput", flow.InputSchema));
        if (flow.ResponseSchema is not null)
        {
            model.Append('\n');
            model.Append(RenderInterface("ResponseActionOutput", flow.ResponseSchema));
        }
        LogicFlowCodegen.WriteText(Path.Combine(generatedDir, "models", $"{modelName}Model.ts"), model.ToString());

        var outputType = flow.ResponseSchema is not null ? "ResponseActionOutput" : "void";
        var service = new StringBuilder(Header);
        service.Append('\n');
        service.Append("import type { IOperationResult } from '@microsoft/power-apps/data';\n");
        service.Append($"import type {{ ManualTriggerInput }} from '../models/{modelName}Model';\n");
        if (flow.ResponseSchema is not null) service.Append($"import type {{ ResponseActionOutput }} from '../models/{modelName}Model';\n");
        service.Append("import { dataSourcesInfo } from '../../../.power/schemas/appschemas/dataSourcesInfo';\n");
        service.Append("import { getClient } from '@microsoft/power-apps/data';\n");
        service.Append('\n');
        service.Append($"export class {modelName}Service {{\n");
        service.Append($"  private static readonly dataSourceName = '{dataSourceName}';\n");
        service.Append('\n');
        service.Append("  private static readonly client = getClient(dataSourcesInfo);\n");
        service.Append('\n');
        service.Append($"  public static async Run(input: ManualTriggerInput): Promise<IOperationResult<{outputType}>> {{\n");
        service.Append("    const params: { input: ManualTriggerInput } = { input };\n");
        service.Append($"    const allParams = {{ ...params, \"api-version\": \"{LogicFlowCodegen.ApiVersion}\" }};\n");
        service.Append($"    const result = await {modelName}Service.client.executeAsync<{{ input: ManualTriggerInput }}, {outputType}>(\n");
        service.Append("      {\n");
        service.Append("        connectorOperation: {\n");
        service.Append($"          tableName: {modelName}Service.dataSourceName,\n");
        service.Append("          operationName: 'Run',\n");
        service.Append("          parameters: allParams\n");
        service.Append("        },\n");
        service.Append("      });\n");
        service.Append("    return result;\n");
        service.Append("  }\n");
        service.Append("}\n");
        LogicFlowCodegen.WriteText(Path.Combine(generatedDir, "services", $"{modelName}Service.ts"), service.ToString());

        var indexPath = Path.Combine(generatedDir, "index.ts");
        var indexLines = File.ReadAllLines(indexPath).ToList();
        InsertExport(indexLines, "// Models", $"export * as {modelName}Model from './models/{modelName}Model';");
        InsertExport(indexLines, "// Services", $"export * from './services/{modelName}Service';");
        LogicFlowCodegen.WriteText(indexPath, string.Join("\n", indexLines) + "\n");
    }

    private static string RenderInterface(string name, JsonObject schema)
    {
        if (schema["properties"] is not JsonObject properties || properties.Count == 0) return $"export type {name} = object;\n";

        var required = new HashSet<string?>((schema["required"] as JsonArray)?.Select(r => (string?)r) ?? Enumerable.Empty<string?>());
        var sb = new StringBuilder($"export interface {name} {{\n");
        foreach (var property in properties)
        {
            if (property.Value?["description"] is JsonValue description)
            {
                foreach (var line in ((string)description!).Split('\n')) sb.Append($"  // {line.TrimEnd('\r')}\n");
            }

            var identifier = TypeScriptIdentifier.From(property.Key, stripWhitespace: false);
            var key = identifier == property.Key ? property.Key : $"'{property.Key.Replace("'", "\\'")}'";
            var optional = required.Contains(property.Key) ? "" : "?";
            sb.Append($"  {key}{optional}: {TsType(property.Value)};\n");
        }
        sb.Append("}\n");
        return sb.ToString();
    }

    private static string TsType(JsonNode? prop)
    {
        if (prop?["enum"] is JsonArray values && values.Count > 0)
            return string.Join(" | ", values.Select(v => $"'{v?.ToString().Replace("\\", "\\\\").Replace("'", "\\'")}'"));

        return (string?)prop?["type"] switch
        {
            "string" => "string",
            "number" or "integer" => "number",
            "boolean" => "boolean",
            "object" => "Record<string, unknown>",
            _ => "unknown",
        };
    }

    private static void InsertExport(List<string> lines, string section, string export)
    {
        if (lines.Contains(export)) return;
        var sectionIndex = lines.FindIndex(l => l.Contains(section));
        if (sectionIndex < 0)
        {
            lines.Add(export);
            return;
        }
        var insertIndex = lines.FindIndex(sectionIndex + 1, l => l.Trim() == "");
        lines.Insert(insertIndex < 0 ? lines.Count : insertIndex, export);
    }
}
